#!/usr/bin/env bash
# =============================================================================
# bootstrap.sh — example_bnlearn の全実験 (最大親数 2 / 3 / 4 の 3 掃引)
#   1 掃引あたり 5 ネットワーク x 7 サンプル数 x 10 反復 x 3 スコア = 1050 実行、
#   3 掃引で 3150 実行。出力は results_p<最大親数>/ に分かれる。
#
# -----------------------------------------------------------------------------
# ITERS の決め方 — 変数数 D とサンプル数 N から決める
# -----------------------------------------------------------------------------
# (1) Hill-Climb は成長段階では 1 反復に 1 辺しか足せない。したがって必要な
#     反復数の下限は「学習される辺の本数 |E|」そのものである。
# (2) |E| <= D x P_eff。P_eff は 1 ノードが実際に持てる親の数で
#         P_eff = min(MAX_PARENTS, floor(log_r(N / 10)))
#     r は 1 変数の状態数。親を P 個持つノードの CPT は r^P 通りの親設定を持ち、
#     1 設定あたり 10 サンプル程度は無いと罰則付きスコアはその親を保持しない。
# (3) 成長後の修正 (REMOVE / REVERSE) と Tabu が局所最適から抜ける分に、
#     成長段階の 2 倍を見込む:   ITERS = 3 x D x P_eff
#
#   このベンチマークで一番大きいのは sachs の D = 11 で、最大親数の掃引は 4 まで、
#   サンプル数は最大 10000 なので P_eff = 4。したがって
#       ITERS = 3 x 11 x 4 = 132
#   あれば足りる。取りうる有向辺が 11 x 10 = 110 本、正解の辺が最大 17 本
#   (sachs) しかないので当然の値である。既定の ITERS=2000 はその 15 倍あり、
#   下げても上げても結果は変わらないため既定のまま使う。
#   (サンプル数が小さい側、例えば n=100 の survey (r=3) では
#    P_eff = floor(log3(10)) = 2 となり、必要反復はさらに少ない 66)
#
#   ブートストラップを行わない例題なので ITERS_BS は使わない。
# =============================================================================

# 全掃引に共通の設定 (最大親数だけを下の行で振る)
export NETWORKS="asia cancer earthquake sachs survey"
export SAMPLE_SIZES="100 200 500 1000 2000 5000 10000"   # 小標本から漸近まで
export REPLICATES=10                                     # 乱数シード 1..10
export SCORES="bic bdeu k2"
export ITERS=2000        # = 既定値。上の規則からの必要量 132 の 15 倍
export TABU=20
export VIZ_N="100 10000" # 比較図は最小・最大サンプル数だけ描く

RUNDIR=./results_p2 MAX_PARENTS=2 ./run_all.sh
RUNDIR=./results_p3 MAX_PARENTS=3 ./run_all.sh   # 真の最大入次数 (sachs) と同じ
RUNDIR=./results_p4 MAX_PARENTS=4 ./run_all.sh
